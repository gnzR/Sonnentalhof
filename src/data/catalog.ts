export function isLivestockAnimal(itemId?: string | null): boolean {
  return (
    itemId === 'chicken' ||
    itemId === 'cow' ||
    itemId === 'sheep' ||
    itemId === 'goat' ||
    itemId === 'pig'
  );
}

export function createAnimalLifespanMs(): number {
  return Math.round(ANIMAL_AVG_LIFESPAN_MS * (0.833 + Math.random() * 0.334));
}

