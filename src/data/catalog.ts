export function xpRequiredForLevel(level: number): number {
  if (level >= MAX_LEVEL) return 0;
  const base = Math.round(100 * Math.pow(level, 1.38));
  if (level >= 200) {
    return Math.round(base * 1.35 * (1 + (level - 199) * 0.015));
  }
  return base;
}

export function petXpRequiredForLevel(petLevel: number): number {
  if (petLevel >= MAX_LEVEL) return 0;
  return Math.round(45 * Math.pow(petLevel, 1.28));
}

export function fishingXpRequiredForLevel(fishingLevel: number): number {
  if (fishingLevel >= MAX_LEVEL) return 0;
  return Math.round(60 * Math.pow(fishingLevel, 1.32));
}

